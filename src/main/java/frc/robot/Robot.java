package frc.robot;

import edu.wpi.first.wpilibj.TimedRobot;

/**
 * An intentionally empty robot program.
 *
 * <p>It controls no hardware. Its only job is to be a valid, running robot program on the roboRIO
 * so the Driver Station can enable the robot. CTRE devices that are "FRC locked" only actuate (for
 * example, when commanded from Phoenix Tuner X's Control tab) while the Driver Station is enabled,
 * and the Driver Station only reports "Robot Code" once a program like this is running.
 */
public class Robot extends TimedRobot {
  public Robot() {}
}
